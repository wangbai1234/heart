#!/usr/bin/env python3
"""Generate browser/backend locale contracts from one reviewed registry."""
import argparse
import json
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate() -> dict[Path, str]:
    registry = json.loads((ROOT / "config/locales.json").read_text(encoding="utf-8"))
    rows = registry["locales"]
    digest = hashlib.sha256()
    digest.update(json.dumps(registry, sort_keys=True, ensure_ascii=False).encode())
    digest.update((ROOT / 'web/src/i18n/legacy.json').read_bytes())
    digest.update((ROOT / 'web/src/i18n/characterTags.json').read_bytes())
    for row in rows:
        resource = ROOT / f'web/src/i18n/locales/{row["code"]}.json'
        digest.update(resource.read_bytes())
    resource_version = digest.hexdigest()[:20]
    codes = [row["code"] for row in rows]
    if len(set(codes)) != len(codes) or registry["default"] not in codes:
        raise ValueError("Invalid registry codes/default")
    aliases: dict[str, str] = {}
    for row in rows:
        if row["fallback"] not in codes or row["direction"] not in {"ltr", "rtl"}:
            raise ValueError("Invalid fallback/direction")
        for alias in [row["code"], *row["aliases"]]:
            key = alias.lower()
            if key in aliases:
                raise ValueError("Duplicate alias: " + alias)
            aliases[key] = row["code"]
    py = (
        '# Generated by scripts/generate_locales.py; do not edit.\n'
        'from typing import Literal\n\n'
        f'Locale = Literal[{", ".join(repr(code) for code in codes)}]\n'
        f'REGISTRY_VERSION = {registry["version"]}\n'
        f'RESOURCE_VERSION = {resource_version!r}\n'
        f'DEFAULT_LOCALE = {registry["default"]!r}\n'
        f'LOCALE_REGISTRY = { {row["code"]: row for row in rows}!r}\n'
        f'LOCALE_ALIASES = {aliases!r}\n'
        'LANGUAGE_NAMES = {code: item["promptName"] for code, item in LOCALE_REGISTRY.items()}\n'
    )
    ts = (
        '// Generated by scripts/generate_locales.py; do not edit.\n'
        f'export const localeRegistry = {json.dumps(rows, ensure_ascii=False, indent=2)} as const\n'
        f'export const locales = {json.dumps(codes)} as const\n'
        'export type Locale = typeof locales[number]\n'
        f'export const localeAliases: Record<string, Locale> = {json.dumps(aliases, ensure_ascii=False, indent=2)}\n'
        f'export const registryVersion = {registry["version"]}\n'
        f'export const resourceVersion = {resource_version!r}\n'
    )
    # Use the same pinned formatter locally and in CI; never emit two formats.
    import subprocess
    import sys
    py = subprocess.run(
        [sys.executable, '-m', 'ruff', 'format', '--stdin-filename', 'locales.py', '-'],
        input=py, text=True, capture_output=True, check=True,
    ).stdout
    return {ROOT / "backend/heart/locales.py": py, ROOT / "web/src/i18n/registry.ts": ts}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Generated locale contract drift: " + str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
